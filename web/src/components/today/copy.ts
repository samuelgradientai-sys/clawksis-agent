export function todayCopy(locale: string): TodayCopy {
  return locale.toLowerCase().startsWith("es") ? es : en;
}

/** `{name}` → the value; `{name:one|other}` → the word for that count ("1 error", "2 errores"). */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)(?::([^|}]*)\|([^}]*))?\}/g, (match, key: string, one?: string, other?: string) => {
    if (!(key in values)) return match;
    if (one === undefined) return String(values[key]);
    return Number(values[key]) === 1 ? one : (other ?? one);
  });
}
